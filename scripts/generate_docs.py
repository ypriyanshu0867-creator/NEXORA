r"""Generate docs\API_DOCUMENTATION.md and docs\DATABASE_DOCUMENTATION.md from the real code.

  python scripts\generate_docs.py

The API document lists every route actually registered, with its access rule read from the guard that protects it,
and every service error code found in the source. The database document is built from database\schema.sql plus
all migrations. Re-run it after any change so the documents never drift from the application.
"""
import ast
import inspect
import os
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
os.environ.setdefault("SECRET_KEY", secrets.token_hex(32))          # lets the app object be built without a .env
os.environ.setdefault("DB_USER", "docs")

import lint_sql  # noqa: E402

HEADER = "<!-- GENERATED by scripts\\generate_docs.py. Do not edit by hand; re-run the script. -->\n\n"
ROLE_NAMES = {"student": "Student", "teacher": "Teacher", "admin": "Administrator"}
PUBLIC = {"main.index", "main.health", "auth.login", "auth.register"}


def access_of(view, endpoint):
    if endpoint in PUBLIC:
        return "Public"
    kind, roles = getattr(view, "nx_access", ("?", ()))
    return "Any signed-in user" if kind == "login" else " / ".join(ROLE_NAMES[r] for r in roles)


def purpose(view):
    doc = inspect.getdoc(inspect.unwrap(view)) or ""
    return doc.strip().splitlines()[0] if doc.strip() else "—"


def service_errors():
    found = {}
    for path in sorted((ROOT / "app").rglob("*.py")):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf8"))):
            if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "ServiceError" and len(node.args) >= 2:
                code, message = node.args[0], node.args[1]
                status = node.args[2] if len(node.args) > 2 else None
                if isinstance(code, ast.Constant) and isinstance(status, (ast.Constant, type(None))):
                    text = message.value if isinstance(message, ast.Constant) else "(computed message)"
                    found.setdefault(code.value, (status.value if status else 400, text))
    return found


def api_document():
    from app import create_app
    from app.config import Config
    app = create_app(Config)
    groups = {}
    for rule in sorted(app.url_map.iter_rules(), key=lambda r: r.rule):
        if rule.endpoint == "static":
            continue
        view = app.view_functions[rule.endpoint]
        methods = ", ".join(sorted(m for m in rule.methods if m not in ("HEAD", "OPTIONS")))
        groups.setdefault(rule.endpoint.split(".")[0], []).append(
            (methods, rule.rule, access_of(view, rule.endpoint), purpose(view)))
    out = [HEADER, "# NEXORA API and route reference\n\n",
           f"{sum(len(v) for v in groups.values())} routes. Routes under `/api/` return JSON; the others are HTML pages and form posts.\n\n",
           "## Conventions\n\n",
           "* **Authentication:** a signed session cookie (`nexora_session`, HttpOnly, SameSite=Lax). The role is read from the "
           "database on every request.\n",
           "* **CSRF:** every POST needs the token, as a form field `csrf_token` or the header `X-CSRFToken` "
           "(its value is in the page's `<meta name=\"csrf-token\">`).\n",
           "* **Success (JSON):** `{\"ok\": true, \"data\": {...}}`. Decimals are strings (exact); datetimes are ISO-8601 UTC ending in `Z`.\n",
           "* **Failure (JSON):** `{\"ok\": false, \"error\": {\"code\": \"...\", \"message\": \"...\", \"fields\": {...}}, \"retry_after\": n}`; "
           "`fields` and `retry_after` appear only when relevant. HTTP 429 and 503 also send `Retry-After`.\n",
           "* **Wrong role or someone else's record:** 403 for the wrong role; 404 for a record you do not own (ids cannot be probed).\n\n",
           "## Main request bodies\n\n",
           "| Endpoint | JSON body |\n|---|---|\n",
           "| `POST /api/attendance/mark` | `{\"qr\": \"NXR1.…\", \"latitude\": n, \"longitude\": n, \"accuracy\": n, \"location_error\": \"denied\"}` (location fields optional; any `student_id` is ignored) |\n",
           "| `POST /api/teacher/attendance-session` | `{\"assignment_id\": n, \"classroom_id\": n, \"qr_validity_seconds\": 15-600, \"duration_minutes\": 1-240, \"geofence_enabled\": bool, \"latitude\": n, \"longitude\": n, \"radius_m\": 5-1000, \"min_accuracy_m\": 5-500}` |\n",
           "| `POST /api/student/sgpa/calculate` | `{\"semester_number\": 1-8, \"grades\": {\"<subject id>\": \"<grade label>\"}}` or `{\"items\": [{\"credits\": \"4\", \"grade_point\": \"8\"}]}` |\n",
           "| `POST /api/student/cgpa/calculate` | `{}` (official results), `{\"hypothetical\": {\"semester_number\": n, \"grades\": {...}}}` or `{\"items\": [...]}` |\n\n",
           "## Routes\n\n"]
    for group in sorted(groups):
        out.append(f"### {group}\n\n| Method | Path | Access | Purpose |\n|---|---|---|---|\n")
        for methods, path, access, text in groups[group]:
            out.append(f"| {methods} | `{path}` | {access} | {text} |\n")
        out.append("\n")
    out.append("## Error codes\n\nCodes returned in `error.code` by the services, with their HTTP status:\n\n| Code | HTTP | Typical message |\n|---|---|---|\n")
    for code, (status, message) in sorted(service_errors().items()):
        out.append(f"| `{code}` | {status} | {message} |\n")
    out.append("\nGeneric codes from the framework: `authentication_required` (401), `forbidden` (403), `page_not_found` (404), "
               "`method_not_allowed` (405), `bad_request` (400, includes an expired CSRF token), `service_unavailable` (503, database unreachable), "
               "`something_went_wrong` (500; details are logged, never shown).\n")
    return "".join(out)


def database_document():
    tables, order, notes = {}, [], {}

    def add_table(name, body, source):
        cols, keys, fks = {}, [], []
        for part in lint_sql.split_top(body):
            first = part.split()[0].strip("`")
            upper = first.upper()
            if upper == "PRIMARY":
                keys.append(("PRIMARY KEY", re.search(r"\((.*)\)", part).group(1)))
            elif upper == "UNIQUE":
                keys.append(("UNIQUE", part))
            elif upper in ("KEY", "INDEX", "FULLTEXT"):
                keys.append(("INDEX", part))
            elif upper == "CONSTRAINT":
                if "FOREIGN KEY" in part:
                    fks.append(re.sub(r"\s+", " ", part))
                elif "CHECK" in part:
                    keys.append(("CHECK", re.sub(r"\s+", " ", part)))
            else:
                cols[first] = (re.sub(r"\s+", " ", part[len(first):]).strip(), source)
        tables[name] = {"cols": cols, "keys": keys, "fks": fks}
        order.append(name)

    schema = lint_sql.strip_comments((ROOT / "database" / "schema.sql").read_text(encoding="utf8"))
    for m in re.finditer(r"CREATE TABLE\s+(\w+)\s*\(", schema):
        depth, i = 1, m.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(schema[i], 0)
            i += 1
        add_table(m.group(1), schema[m.end():i - 1], "schema")
    for path in sorted((ROOT / "database" / "migrations").glob("[0-9][0-9][0-9]_*.sql")):
        sql = lint_sql.strip_comments(path.read_text(encoding="utf8"))
        tag = path.name[:3]
        for m in re.finditer(r"CREATE TABLE\s+(\w+)\s*\(", sql):
            depth, i = 1, m.end()
            while depth:
                depth += {"(": 1, ")": -1}.get(sql[i], 0)
                i += 1
            add_table(m.group(1), sql[m.end():i - 1], f"migration {tag}")
        for stmt in sql.split(";"):
            alter = re.match(r"\s*ALTER TABLE\s+(\w+)(.*)", stmt, re.S)
            if not alter:
                continue
            table = tables[alter.group(1)]
            for part in lint_sql.split_top(alter.group(2)):
                add = re.match(r"ADD COLUMN\s+(\w+)\s+(.*)", part, re.S)
                mod = re.match(r"MODIFY COLUMN\s+(\w+)\s+(.*)", part, re.S)
                if add:
                    table["cols"][add.group(1)] = (re.sub(r"\s+", " ", add.group(2)).strip(), f"migration {tag}")
                elif mod:
                    table["cols"][mod.group(1)] = (re.sub(r"\s+", " ", mod.group(2)).strip(), f"changed in migration {tag}")
                elif re.match(r"ADD (UNIQUE )?KEY", part):
                    table["keys"].append(("INDEX", re.sub(r"\s+", " ", part) + f"  (migration {tag})"))
                elif part.startswith("ADD CONSTRAINT"):
                    table["fks"].append(re.sub(r"\s+", " ", part[4:]) + f"  (migration {tag})")

    out = [HEADER, "# NEXORA database documentation\n\n",
           f"MySQL 8.x, InnoDB, utf8mb4. {len(tables)} tables (plus `schema_migrations`, created by `scripts\\migrate.py`). "
           "All timestamps are UTC. Built from `database\\schema.sql` and `database\\migrations\\*.sql`.\n\n",
           "## Relationships\n\n"]
    for name in order:
        for fk in tables[name]["fks"]:
            m = re.search(r"FOREIGN KEY\s*\((\w+)\)\s*REFERENCES\s+(\w+)\s*\((\w+)\)(.*)", fk)
            if m:
                out.append(f"* `{name}.{m.group(1)}` → `{m.group(2)}.{m.group(3)}` {m.group(4).strip().split('(migration')[0].strip()}\n")
    out.append("\n## Tables\n\n")
    for name in order:
        t = tables[name]
        out.append(f"### `{name}`\n\n| Column | Definition | Added by |\n|---|---|---|\n")
        for col, (definition, source) in t["cols"].items():
            out.append(f"| `{col}` | {definition} | {source} |\n")
        for kind in ("PRIMARY KEY", "UNIQUE", "INDEX", "CHECK"):
            items = [k for k in t["keys"] if k[0] == kind]
            if items:
                out.append(f"\n**{kind.title() if kind != 'CHECK' else 'Check constraints'}:** " + "; ".join(f"`{i[1]}`" for i in items) + "\n")
        if t["fks"]:
            out.append("\n**Foreign keys:** " + "; ".join(f"`{f}`" for f in t["fks"]) + "\n")
        out.append("\n")
    return "".join(out)


def main():
    docs = ROOT / "docs"
    (docs / "API_DOCUMENTATION.md").write_text(api_document(), encoding="utf8")
    (docs / "DATABASE_DOCUMENTATION.md").write_text(database_document(), encoding="utf8")
    print("Wrote docs\\API_DOCUMENTATION.md and docs\\DATABASE_DOCUMENTATION.md")


if __name__ == "__main__":
    main()
